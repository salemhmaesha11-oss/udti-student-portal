  'الفئة'?: string;
  'تاريخ_تغيير_الفئة'?: string | null;
  'تاريخ الإنشاء'?: string | null;
  'السنه الدراسية'?: string | number;
  class?: string;
  year?: string;
  password?: string;
  name?: string;
  student_id?: string | number;
